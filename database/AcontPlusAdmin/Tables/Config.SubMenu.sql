
CREATE TABLE Config.SubMenu(
	idSubMenu INT PRIMARY KEY IDENTITY(1,1),
	idMenu INT FOREIGN KEY REFERENCES Config.Menu(idMenu),
	codigo NVARCHAR(10) NOT NULL UNIQUE, 
	codMenu VARCHAR(10) NULL,
	descripcion NVARCHAR(150) NOT NULL,
	urlSubMenu NVARCHAR(300) NOT NULL UNIQUE,
	icono NVARCHAR(200) NOT NULL,
	fechaRegistro DATETIME,
	estado BIT DEFAULT 1 
)