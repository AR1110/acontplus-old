using Acontplus.Core.Abstractions.Messaging;
using Acontplus.Infrastructure.Extensions;
using Acontplus.Infrastructure.Messaging;
using Acontplus.S3Application.Models;
using Acontplus.Services.Extensions.Authentication;
using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.IdentityModel.Tokens;
using Restaurant.Application.BackgroundServices;
using Restaurant.Application.Mapping;
using Restaurant.Infrastructure.Extensions;
using Scrutor;
using System.Text;

namespace Restaurant.Api.Extensions;

public static class ApplicationServicesExtensions
{
    public static IServiceCollection AddRestaurantServices(this IServiceCollection services,
        IConfiguration configuration)
    {
        services.AddApplicationServices(configuration);

        services.AddAdvancedLoggingOptions(configuration);

#if DEBUG
        services.AddJwtAuthentication(configuration); //USAR ESTO A FUTURO
#else
        services.AddAuthentication(options =>
        {
            options.DefaultAuthenticateScheme = JwtBearerDefaults.AuthenticationScheme;
            options.DefaultChallengeScheme = JwtBearerDefaults.AuthenticationScheme;
        })
           .AddJwtBearer(options =>
           {
               options.TokenValidationParameters = new TokenValidationParameters
               {
                   RequireExpirationTime = true,
                   ValidateIssuer = false,
                   ValidateAudience = false,
                   ValidateLifetime = true,
                   ValidateIssuerSigningKey = true,
                   ClockSkew = TimeSpan.FromSeconds(0),
                   IssuerSigningKey = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(configuration["JwtSettings:SecurityKey"] ?? throw new InvalidOperationException()))
               };
           });

        services.AddAuthorization();
        services.AddAuthorizationBuilder();

#endif

        services.AddOpenApi();

        services.AddHttpContextAccessor();

        services.AddResponseCompression();

        // Register Application Mappings -> Mapster
        services.RegisterMappings();

        JsonConfigurationService.ConfigureAspNetCore(services, false);

        //services.AddLookupService();

        // Register Event Bus from Acontplus.Infrastructure (InMemoryEventBus with Channels)
        // Provides IEventPublisher and IEventSubscriber for high-performance async event processing
        services.AddSingleton<InMemoryEventBus>();
        services.AddSingleton<IEventPublisher>(sp => sp.GetRequiredService<InMemoryEventBus>());
        services.AddSingleton<IEventSubscriber>(sp => sp.GetRequiredService<InMemoryEventBus>());

        // Register Background Service to process events
        services.AddHostedService<MealPlanAutoGeneratedEventHandler>();

        services.AddRestaurantInfrastructure(configuration);

        // Add Caching Services
        services.AddCachingServices(configuration);

        string[] scopedNameSpaces =
        [
            "Restaurant.Application.Services",
            "Restaurant.Application.Services.MealManagement",
            "Restaurant.Infrastructure.Persistence.Repositories",
            "Acontplus.S3Application.Services",
            "Acontplus.Persistence.SqlServer.Repositories",
            "Acontplus.Services.Extensions.Context",
            "Acontplus.Services.Services.Implementations"
        ];

        services.Scan(scan => scan
            .FromApplicationDependencies()
            .AddClasses(classes => classes.InNamespaces(scopedNameSpaces))
            .UsingRegistrationStrategy(RegistrationStrategy.Skip)
            .AsImplementedInterfaces()
            .WithScopedLifetime()
        );

        services.AddTransient<S3ObjectCustom>();

        return services;
    }
}
